#!/usr/bin/env bash
# Renders the spoken navigation phrases into a single C array so the board can
# play them without any network or phone involvement.
#
# Why pre-rendered files instead of streaming TTS: the BLE link carries about
# 100 kbit/s, while 16 kHz speech needs 256 kbit/s. A streamed sentence would
# break up exactly when the rider needs it. A flash-resident clip starts on the
# same millisecond the cue fires.
#
# Sample rate: the codec plays at 22050 Hz, but the clips are stored at 16 kHz
# mono 16-bit. That is a third less flash for no audible loss on a 2 W speaker,
# and playback resamples with linear interpolation.
set -euo pipefail

repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${repo_dir}"

out="shared/audio/src/moto_voice_phrases.c"
voice="${VOICE:-Tingting}"
rate=16000

# Order must match moto_voice_phrase_t in shared/audio/include/moto_audio_tones.h.
phrases=(
  "前方左转"
  "前方右转"
  "前方掉头"
  "前方环岛"
  "已到达目的地"
  "前方拥堵"
  "前方缓行"
  "已偏航，正在重新规划"
  "请减速"
  "注意安全"
)

tmp="$(mktemp -d)"
trap 'rm -rf "${tmp}"' EXIT

{
  echo "// Generated by scripts/generate_voice_phrases.sh -- do not edit."
  echo "// Voice: ${voice}, ${rate} Hz mono 16-bit PCM."
  echo "#include <stdint.h>"
  echo "#include \"moto_audio_tones.h\""
  echo ""
} > "${out}"

offsets=()
lengths=()
total=0
for i in "${!phrases[@]}"; do
  text="${phrases[$i]}"
  say -v "${voice}" -o "${tmp}/p.aiff" "${text}"
  # Trim leading/trailing silence so a cue starts the instant it is queued.
  afconvert -f WAVE -d LEI16@${rate} -c 1 "${tmp}/p.aiff" "${tmp}/p.wav"
  python3 - "${tmp}/p.wav" "${tmp}/p.raw" <<'PYTHON'
import struct, sys, wave
src, dst = sys.argv[1], sys.argv[2]
with wave.open(src, "rb") as w:
    frames = w.readframes(w.getnframes())
samples = struct.unpack("<%dh" % (len(frames) // 2), frames)
# Keep 15 ms of lead-in and 40 ms of tail so the clip does not start mid-word
# but also does not wait before speaking.
lead = int(0.015 * 16000)
tail = int(0.040 * 16000)
peak = max((abs(s) for s in samples), default=0)
# Normalise to just under half scale: the NS4150B amplifier is loud and the
# speaker is small.
gain = (16384 / peak) if peak > 0 else 1.0
trimmed = [max(-32768, min(32767, int(s * gain))) for s in samples]
trimmed = [0] * lead + trimmed + [0] * tail
with open(dst, "wb") as f:
    f.write(struct.pack("<%dh" % len(trimmed), *trimmed))
PYTHON
  bytes="$(stat -f%z "${tmp}/p.raw")"
  offsets+=("${total}")
  lengths+=("${bytes}")
  total=$(( total + bytes ))
  echo "  // ${i}: ${text} (${bytes} bytes)" >> "${out}"
done

echo "" >> "${out}"
echo "const uint32_t moto_voice_blob_bytes = ${total}u;" >> "${out}"
echo "" >> "${out}"
# uint32_t: the whole blob exceeds 65535 bytes, so 16-bit offsets would wrap.
echo "static const uint32_t kOffsets[${#offsets[@]}] = { $(IFS=,; echo "${offsets[*]}") };" >> "${out}"
echo "static const uint32_t kLengths[${#lengths[@]}] = { $(IFS=,; echo "${lengths[*]}") };" >> "${out}"
echo "" >> "${out}"
echo "static const uint8_t kBlob[${total}] = {" >> "${out}"

for i in "${!phrases[@]}"; do
  echo "  // ${i}" >> "${out}"
  say -v "${voice}" -o "${tmp}/p.aiff" "${phrases[$i]}"
  afconvert -f WAVE -d LEI16@${rate} -c 1 "${tmp}/p.aiff" "${tmp}/p.wav"
  python3 - "${tmp}/p.wav" "${tmp}/p.raw" <<'PYTHON' >> "${out}"
import struct, sys, wave
with wave.open(sys.argv[1], "rb") as w:
    frames = w.readframes(w.getnframes())
samples = struct.unpack("<%dh" % (len(frames) // 2), frames)
lead = int(0.015 * 16000); tail = int(0.040 * 16000)
peak = max((abs(s) for s in samples), default=0)
gain = (16384 / peak) if peak > 0 else 1.0
trimmed = [max(-32768, min(32767, int(s * gain))) for s in samples]
trimmed = [0] * lead + trimmed + [0] * tail
raw = struct.pack("<%dh" % len(trimmed), *trimmed)
for i in range(0, len(raw), 24):
    print("  " + ",".join(str(b) for b in raw[i:i+24]) + ",")
PYTHON
done

echo "};" >> "${out}"
echo "" >> "${out}"
echo "bool moto_voice_phrase_data(moto_voice_phrase_t phrase, const uint8_t** data," >> "${out}"
echo "                               uint32_t* length) {" >> "${out}"
echo "    const int index = (int)phrase;" >> "${out}"
echo "    if (index < 0 || index >= ${#offsets[@]}) return false;" >> "${out}"
echo "    *data = kBlob + kOffsets[index];" >> "${out}"
echo "    *length = kLengths[index];" >> "${out}"
echo "    return true;" >> "${out}"
echo "}" >> "${out}"

echo "wrote ${out}: ${#phrases[@]} phrases, $(( total / 1024 )) KB"
